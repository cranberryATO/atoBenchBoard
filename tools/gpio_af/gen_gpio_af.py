"""Generate the GPIO alternate function table from the STM32CubeMX database.

The output is a complete C source file defining ato_gpio_af_by_port (see
Inc/ato_gpio_af.h): for each port and pin, the name of the signal of each
AF number, NULL when there is none. Signals sharing an AF are joined with '/'.

Example (from the project root):
    uv run tools/gpio_af/gen_gpio_af.py -o Src/ato_gpio_af_g47x.c
"""

import argparse
import re
import sys
import textwrap
import xml.etree.ElementTree as ET
from pathlib import Path

DEFAULT_XML = (Path.home() / "STM32CubeMX/db/mcu/IP"
               / "GPIO-STM32G47x_gpio_v1_0_Modes.xml")
PORTS = "ABCDEFG"  # must match ATO_GPIO_AF_NB_PORTS
NB_PINS = 16
NB_AF = 16


def local_name(tag: str) -> str:
    """Tag without its XML namespace."""
    return tag.rsplit("}", 1)[-1]


def parse(xml_path: Path) -> dict[str, dict[int, dict[int, list[str]]]]:
    """Return {port letter: {pin: {af: [signal names]}}}."""
    table: dict[str, dict[int, dict[int, list[str]]]] = {}
    root = ET.parse(xml_path).getroot()
    for pin in root.iter():
        if local_name(pin.tag) != "GPIO_Pin":
            continue
        m = re.fullmatch(r"P([A-Z])(\d+)", pin.get("Name", ""))
        if not m:
            continue  # not a GPIO (power, oscillator...)
        port, num = m.group(1), int(m.group(2))
        for signal in pin:
            if local_name(signal.tag) != "PinSignal":
                continue
            for value in signal.iter():
                if local_name(value.tag) != "PossibleValue" or not value.text:
                    continue
                af = re.match(r"GPIO_AF(\d+)_", value.text)
                if af is None:
                    continue  # analog or additional function, not an AF
                (table.setdefault(port, {}).setdefault(num, {})
                 .setdefault(int(af.group(1)), []).append(signal.get("Name")))
    return table


def generate(table: dict, xml_path: Path, family: str) -> str:
    out = [
        "// GENERATED FILE, DO NOT EDIT.",
        "// Generated by tools/gpio_af/gen_gpio_af.py from the STM32CubeMX",
        f"// database file {xml_path.name}.",
        f"// Alternate functions of the {family}, indexed [port][pin][AF number];",
        "// NULL: no function. Signals sharing an AF are joined with '/'. All the",
        "// pins of the family are listed, whatever the package.",
        "",
        '#include "ato_gpio_af.h"',
        "",
        "#include <stddef.h>",
        "",
    ]
    for port in PORTS:
        pins = table.get(port)
        if not pins:
            continue
        out.append(f"static const ato_gpio_af_row_t gpio{port.lower()}_af[{NB_PINS}] = {{")
        for num in sorted(pins):
            if num >= NB_PINS:
                sys.exit(f"P{port}{num}: pin number out of range")
            out.append(f"    [{num}] =")
            out.append("        {")
            for af in sorted(pins[num]):
                if af >= NB_AF:
                    sys.exit(f"P{port}{num}: AF{af} out of range")
                names = "/".join(sorted(set(pins[num][af])))
                out.append(f'            [{af}] = "{names}",')
            out.append("        },")
        out.append("};")
        out.append("")

    unknown = sorted(set(table) - set(PORTS))
    if unknown:
        sys.exit(f"ports not handled: {', '.join(unknown)}")

    out.append("const ato_gpio_af_row_t *const "
               "ato_gpio_af_by_port[ATO_GPIO_AF_NB_PORTS] = {")
    # NULL: no pin of this port in the family; packed as clang-format does
    rows = [f"gpio{port.lower()}_af" if port in table else "NULL"
            for port in PORTS]
    out.extend(textwrap.wrap(", ".join(rows) + ",", width=80,
                             initial_indent="    ", subsequent_indent="    "))
    out.append("};")
    return "\n".join(out) + "\n"


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("xml", nargs="?", type=Path, default=DEFAULT_XML,
                   help=f"CubeMX GPIO modes file (default: {DEFAULT_XML})")
    p.add_argument("-o", "--output", type=Path,
                   help="output C file (default: standard output)")
    args = p.parse_args()

    m = re.search(r"GPIO-(STM32\w+?)_gpio", args.xml.name)
    family = m.group(1) if m else args.xml.stem
    text = generate(parse(args.xml), args.xml, family)
    if args.output:
        args.output.write_text(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
