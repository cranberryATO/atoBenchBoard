/* This function implements the behaviour of a command, so must have the correct
   prototype. */
static BaseType_t prvTaskStatsCommand(char *pcWriteBuffer,
                                      size_t xWriteBufferLen,
                                      const char *pcCommandString) {
  /* For simplicity, this function assumes the output buffer is large enough
     to hold all the text generated by executing the vTaskList() API function,
     so the xWriteBufferLen parameter is not used. */
  (void)xWriteBufferLen;

  /* pcWriteBuffer is used directly as the vTaskList() parameter, so the table
     generated by executing vTaskList() is written directly into the output
     buffer. */
  vTaskList(pcWriteBuffer /*+ strlen(pcHeader)*/);

  /* The entire table was written directly to the output buffer. Execution
     of this command is complete, so return pdFALSE. */
  return pdFALSE;
}

static const CLI_Command_Definition_t xTasksCommand = {
    "ps", "\r\nps:\r\n Show FreeRTOS Tasks\r\n\r\n", prvTaskStatsCommand, 0};

static BaseType_t prvStackOverflow(char *pcWriteBuffer, size_t xWriteBufferLen,
                                   const char *pcCommandString) {
  int onStack[512];
  for (int i = 0; i < 512; i++) {
    onStack[i] = 0xbaadfeed;
  }
  memcpy(pcWriteBuffer, onStack, xWriteBufferLen);
  return pdFALSE;
}

static const CLI_Command_Definition_t xStackOverflowCommand = {
    "so", "\r\nso:\r\n Stack Overflow\r\n\r\n", prvStackOverflow, 0};

static BaseType_t prvStatsCommand(char *pcWriteBuffer, size_t xWriteBufferLen,
                                  const char *pcCommandString) {
  (void)pcCommandString;
  snprintf(pcWriteBuffer, xWriteBufferLen,
           "tx dropped bytes : %lu\r\n"
           "uart rx errors   : %lu\r\n"
           "uart tx errors   : %lu\r\n"
           "rx restart fails : %lu\r\n",
           (unsigned long)tx_dropped_bytes, (unsigned long)uart_rx_errors,
           (unsigned long)uart_tx_errors,
           (unsigned long)uart_rx_restart_failures);
  return pdFALSE;
}

static const CLI_Command_Definition_t xStatsCommand = {
    "stats", "\r\nstats:\r\n Show UART error and drop counters\r\n\r\n",
    prvStatsCommand, 0};

